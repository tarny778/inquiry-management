-- =========================================================
-- テスト：問題解決を確認する
-- 2026-10-07
--
-- 業務上の状態：
--   問い合わせ者が提示された解決方法を確認し、
--   問題が解決したことを確認する。
--
-- 今回のテストでは、この問い合わせに必要な問題が
-- 1件だけなので、問題解決確認と同時に
-- 問い合わせ全体も対応完了とする。
--
-- 状態：
--   問い合わせ者確認待ち
--        ↓
--   問題解決確認済み
--        ↓
--   問い合わせ対応完了
-- =========================================================

-- =========================================================
-- ① 問い合わせ問題の解決確認を記録する
-- =========================================================

UPDATE "問い合わせ問題"
SET
    "現在の調査状況" = '問題解決確認済み',
    "問題解決確認日時" = CURRENT_TIMESTAMP
WHERE
    "問題番号" = 1
    AND "問い合わせ番号" = 1;

-- =========================================================
-- ② 問い合わせ全体の対応完了を記録する
-- =========================================================

UPDATE "問い合わせ"
SET
    "対応完了日時" = CURRENT_TIMESTAMP
WHERE
    "問い合わせ番号" = 1;