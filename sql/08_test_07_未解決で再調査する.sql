-- 業務上の状態：
--   問い合わせ者が「まだ解決していない」と回答したため、
--   問い合わせ問題を再び調査中の状態に戻す。
--
-- この時点では、
--   ・問題レコードの原因・対応内容は残す
--   ・問題レコードの最新更新日時も変更しない
--   ・問い合わせ問題は再び調査中となる
--   ・最新NG日時に今回のNG日時を記録する
--   ・調査を終えた日時はNULLのまま保持する
--   ・調査開始日時は最初の調査開始日時を保持する
--
-- 状態：
--   リアクション待ち（2）
--       ↓
--   問い合わせ者NG
--       ↓
--   調査中（1）
-- =========================================================


-- =========================================================
-- ① 問い合わせ問題を再調査中に戻す
-- =========================================================

UPDATE "問い合わせ問題"
SET
    "問い合わせ問題状態" = 1,
    "調査を終えた日時" = NULL,
    "最新NG日時" = CURRENT_TIMESTAMP
WHERE
    "問題番号" = (
        SELECT MAX("問題番号")
        FROM "問題"
    )
    AND "問い合わせ番号" = (
        SELECT MAX("問い合わせ番号")
        FROM "問い合わせ"
    );