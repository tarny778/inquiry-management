-- テスト：問い合わせ者がOKする
-- 2026-10-08
--
-- 業務上の状態：
--   問い合わせ者が、提示された解決方法で問題が解決したと回答する。
--
-- この時点では、
--   ・問い合わせ問題は「調査無事終了」とする
--   ・調査を終えた日時を記録する
--   ・問い合わせ全体の対応完了日時は変更しない
--
-- 問い合わせ全体の対応完了は、
--   対応担当者が別途「対応完了」とすることで行う。
--
-- 状態：
--   リアクション待ち（2）
--       ↓
--   問い合わせ者がOK
--       ↓
--   調査無事終了（3）
-- =========================================================

UPDATE "問い合わせ問題"
SET
    "問い合わせ問題状態" = 3,
    "現在の調査状況" = '問題解決を確認済み',
    "調査を終えた日時" = CURRENT_TIMESTAMP
WHERE
    "問題番号" = (
        SELECT MAX("問題番号")
        FROM "問題"
    )
    AND "問い合わせ番号" = (
        SELECT MAX("問い合わせ番号")
        FROM "問い合わせ"
    );