
-- =========================================================
-- テスト：問い合わせ者がNGと回答
-- 2026-10-12
--
-- 業務上の状態：
--   問い合わせ者が「まだ解決していない」と回答したため、
--   次の問題調査へ移行する。
--
-- この時点では、
--   ・旧問い合わせ問題調査は「NGで移行先へ」とする
--   ・リアクション内容と日時を記録する
--   ・移行先が調査中なら、その問題調査に合流する
--   ・移行先が存在しない、または調査中でなければ、
--     新たな問題調査を作成する
--   ・新たな問い合わせ問題調査を作成する
--   ・旧問題調査に移行先の問題調査番号を記録する
-- =========================================================

DO $$
DECLARE
    v_old_investigation "問題調査"%ROWTYPE;
    v_old_relation "問い合わせ問題調査"%ROWTYPE;

    v_target_investigation_no
        "問題調査"."問題調査番号"%TYPE;

    v_now TIMESTAMP := CURRENT_TIMESTAMP;
BEGIN
    -- =====================================================
    -- ① 今回の問題調査と問い合わせ問題調査を取得する
    -- =====================================================

    SELECT *
    INTO v_old_investigation
    FROM "問題調査"
    WHERE "問題調査番号" = (
        SELECT MAX("問題調査番号")
        FROM "問題調査"
    );

    SELECT *
    INTO v_old_relation
    FROM "問い合わせ問題調査"
    WHERE "問題調査番号" =
          v_old_investigation."問題調査番号"
      AND "問い合わせ番号" = (
          SELECT MAX("問い合わせ番号")
          FROM "問い合わせ"
      );

    -- =====================================================
    -- ② 旧問題調査の移行先が調査中かを確認する
    -- =====================================================

    SELECT "問題調査番号"
    INTO v_target_investigation_no
    FROM "問題調査"
    WHERE "問題調査番号" =
          v_old_investigation."最新移行先の問題調査番号"
      AND "問題調査状態" = 1;

    -- =====================================================
    -- ③ 移行先がなければ、新しい問題調査を作成する
    -- =====================================================

    IF v_target_investigation_no IS NULL THEN

        INSERT INTO "問題調査" (
            "問題調査の名称や仮説",
            "問題の原因",
            "情シス側での対応",
            "問い合わせ者側で必要な対応"
        )
        VALUES (
            v_old_investigation."問題調査の名称や仮説"
                || 'から複写',
            v_old_investigation."問題の原因",
            v_old_investigation."情シス側での対応",
            v_old_investigation."問い合わせ者側で必要な対応"
        )
        RETURNING "問題調査番号"
        INTO v_target_investigation_no;

        -- 旧問題調査に移行先を記録する
        UPDATE "問題調査"
        SET "最新移行先の問題調査番号" =
            v_target_investigation_no
        WHERE "問題調査番号" =
            v_old_investigation."問題調査番号";

    END IF;

    -- =====================================================
    -- ④ 旧問い合わせ問題調査をNGで移行先へとする
    -- =====================================================

    UPDATE "問い合わせ問題調査"
    SET
        "問い合わせ問題調査状態" = 5,
        "リアクション内容" = 2,
        "リアクション日時" = v_now,
        "NGでの移行先問題調査番号" =
            v_target_investigation_no
    WHERE "問い合わせ問題調査番号" =
          v_old_relation."問い合わせ問題調査番号";

    -- =====================================================
    -- ⑤ 移行先の問題調査に問い合わせを関連付ける
    -- =====================================================

    INSERT INTO "問い合わせ問題調査" (
        "問題調査番号",
        "問い合わせ番号"
    )
    VALUES (
        v_target_investigation_no,
        v_old_relation."問い合わせ番号"
    );

END $$;
