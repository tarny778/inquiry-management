
-- =========================================================
-- テスト：問い合わせ者がNGと回答
-- 2026-10-12
--
-- 業務上の状態：
--   問い合わせ者が「まだ解決していない」と回答したため、
--   次の調査へ移行する。
--
-- この時点では、
--   ・旧問い合わせ調査は「NGで移行先へ」とする
--   ・リアクション内容と日時を記録する
--   ・移行先が調査中なら、その調査に合流する
--   ・移行先が存在しない、または調査中でなければ、
--     新たな調査を作成する
--   ・新たな問い合わせ調査を作成する
--   ・旧調査に移行先の調査番号を記録する
-- =========================================================

DO $$
DECLARE
    v_old_investigation "調査"%ROWTYPE;
    v_old_relation "問い合わせ調査"%ROWTYPE;

    v_target_investigation_no
        "調査"."調査番号"%TYPE;

    v_now TIMESTAMPTZ := CURRENT_TIMESTAMP;
BEGIN
    -- =====================================================
    -- ① 今回の調査と問い合わせ調査を取得する
    -- =====================================================

    SELECT *
    INTO v_old_investigation
    FROM "調査"
    WHERE "調査番号" = (
        SELECT MAX("調査番号")
        FROM "調査"
    );

    SELECT *
    INTO v_old_relation
    FROM "問い合わせ調査"
    WHERE "調査番号" =
          v_old_investigation."調査番号"
      AND "問い合わせ番号" = (
          SELECT MAX("問い合わせ番号")
          FROM "問い合わせ"
      );

    -- =====================================================
    -- ② 旧調査の移行先が調査中かを確認する
    -- =====================================================

    SELECT "調査番号"
    INTO v_target_investigation_no
    FROM "調査"
    WHERE "調査番号" =
          v_old_investigation."最新移行先の調査番号"
      AND "調査状態" = 1;

    -- =====================================================
    -- ③ 移行先がなければ、新しい調査を作成する
    -- =====================================================

    IF v_target_investigation_no IS NULL THEN

        INSERT INTO "調査" (
            "調査の名称",
            "原因・仮説",
            "情シス側での対応",
            "問い合わせ者側で必要な対応"
        )
        VALUES (
            v_old_investigation."調査の名称"
                || 'から複写',
            v_old_investigation."原因・仮説",
            v_old_investigation."情シス側での対応",
            v_old_investigation."問い合わせ者側で必要な対応"
        )
        RETURNING "調査番号"
        INTO v_target_investigation_no;

        -- 旧調査に移行先を記録する
        UPDATE "調査"
        SET "最新移行先の調査番号" =
            v_target_investigation_no
        WHERE "調査番号" =
            v_old_investigation."調査番号";

    END IF;

    -- =====================================================
    -- ④ 旧問い合わせ調査をNGで移行先へとする
    -- =====================================================

    UPDATE "問い合わせ調査"
    SET
        "問い合わせ調査状態" = 5,
        "リアクション内容" = 2,
        "リアクション日時" = v_now,
        "NGでの移行先調査番号" =
            v_target_investigation_no
    WHERE "問い合わせ調査番号" =
          v_old_relation."問い合わせ調査番号";

    -- =====================================================
    -- ⑤ 移行先の調査に問い合わせを関連付ける
    -- =====================================================

    INSERT INTO "問い合わせ調査" (
        "調査番号",
        "問い合わせ番号"
    )
    VALUES (
        v_target_investigation_no,
        v_old_relation."問い合わせ番号"
    );

END $$;
