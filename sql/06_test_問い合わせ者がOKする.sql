-- =========================================================
-- テスト：問い合わせ者がOKする
-- 2026-10-12
--
-- 業務上の状態：
--   問い合わせ者が、提示された解決方法で問題が解決したと回答する。
--
-- この時点では、
--   ・問い合わせ調査は「OKで完了=4」とする
--   ・リアクション日時とリアクション内容=1を記録する
--   ・問い合わせ全体の対応完了日時は変更しない
--
-- 問い合わせ全体の対応完了は、
--   対応担当者が別途「対応完了」とすることで行う。
--
-- 状態：
--   リアクション待ち（3）
--       ↓
--   問い合わせ者がOK
--       ↓
--   OKで完了（4）
-- =========================================================

UPDATE "問い合わせ調査"
SET
    "問い合わせ調査状態" = 4,
    "リアクション内容" = 1,
    "リアクション日時" = CURRENT_TIMESTAMP
WHERE
    "調査番号" = (
        SELECT MAX("調査番号")
        FROM "調査"
    )
    AND "問い合わせ番号" = (
        SELECT MAX("問い合わせ番号")
        FROM "問い合わせ"
    );