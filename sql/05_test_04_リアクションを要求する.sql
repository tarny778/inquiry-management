-- =========================================================
-- テスト：リアクションを要求する
-- 2026-10-08
--
-- 業務上の状態：
--   対応担当者が調査結果を問題テーブルに反映し、
--   問い合わせ者に解決したかどうかのリアクションを要求する。
--
-- この時点では、
--   ・問い合わせ問題はまだ閉じない
--   ・問い合わせ問題状態は「リアクション待ち」とする
--   ・調査を終えた日時はNULLのまま
--   ・最新NG日時はNULLのまま
--   ・リアクション要求最新日時を記録する
--
-- 状態：
--   調査中（1）
--       ↓
--   リアクション待ち（2）
-- =========================================================


-- =========================================================
-- ① 問題の原因と対応を最新情報に更新する
-- =========================================================

UPDATE "問題"
SET
    "問題の原因" = '電源ユニットの故障',
    "情シス側での対応" = '電源ユニットを交換する',
    "問い合わせ者側で必要な対応" = 'PCの電源が入ることを確認する',
    "原因と対応の最新更新日時" = CURRENT_TIMESTAMP
WHERE
    "問題番号" = (
        SELECT MAX("問題番号")
        FROM "問題"
    );


-- =========================================================
-- ② 問い合わせ問題をリアクション待ちにする
-- =========================================================

UPDATE "問い合わせ問題"
SET
    "問い合わせ問題状態" = 2,
    "現在の調査状況" = '原因と対応を整理し、問い合わせ者の確認待ち',
    "リアクション要求最新日時" = CURRENT_TIMESTAMP
WHERE
    "問題番号" = (
        SELECT MAX("問題番号")
        FROM "問題"
    )
    AND "問い合わせ番号" = (
        SELECT MAX("問い合わせ番号")
        FROM "問い合わせ"
    );