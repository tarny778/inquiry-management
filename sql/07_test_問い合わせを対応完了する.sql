-- =========================================================
-- テスト：問い合わせを対応完了する
-- 2026-10-12
--
-- 業務上の状態：
--   対応担当者が、問い合わせ全体について必要な対応が完了したと判断し、
--   「対応完了」とする。
--
-- この操作により、
--   ・問い合わせの対応完了日時を記録する
--   ・問い合わせ全体の状態は「対応完了」となる
--
-- 問い合わせ調査の「OKで完了」と、
-- 問い合わせ全体の「対応完了」は別の状態である。
--
-- 状態：
--   問い合わせ全体：対応中
--       ↓
--   対応担当者が対応完了
--       ↓
--   問い合わせ全体：対応完了
-- =========================================================

UPDATE "問い合わせ"
SET
    "対応完了日時" = CURRENT_TIMESTAMP
WHERE
    "問い合わせ番号" = (
        SELECT MAX("問い合わせ番号")
        FROM "問い合わせ"
    );