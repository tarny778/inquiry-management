
-- =========================================================
-- テスト：リアクションを要求する
-- 2026-10-12
--
-- 業務上の状態：
--   対応担当者が調査結果を調査テーブルに反映し、
--   問い合わせ者に解決したかどうかのリアクションを要求する。
--
-- この時点では、
--   ・問い合わせ調査はまだ閉じない
--   ・問い合わせ調査状態は「リアクション待ち」とする
--   ・調査の状態は「リアクション要求済み」とする
--   ・調査のリアクション要求日時を記録する
--
-- 状態：
--   問い合わせ調査状態
--   調査中（1）
--       ↓
--   リアクション待ち（3）
--
--   調査状態
--   調査中（1）
--       ↓
--   リアクション要求済み（2）
-- =========================================================


-- =========================================================
-- ① 調査レコードにおいて原因と対応を更新する
-- =========================================================

UPDATE "調査"
SET
    "原因・仮説" = '電源ユニットの故障',
    "情シス側での対応" = '電源ユニットを交換する',
    "問い合わせ者側で必要な対応" = 'PCの電源が入ることを確認する'
WHERE
    "調査番号" = (
        SELECT MAX("調査番号")
        FROM "調査"
    );


-- =========================================================
-- ② 調査をリアクション要求済みにし、
--    関連する問い合わせ調査のうち、
--    調査中のものをリアクション待ちにする
-- =========================================================

UPDATE "調査"
SET
    "調査状態" = 2,
    "リアクション要求日時" = CURRENT_TIMESTAMP
WHERE
    "調査番号" = (
        SELECT MAX("調査番号")
        FROM "調査"
    );

UPDATE "問い合わせ調査"
SET
    "問い合わせ調査状態" = 3,
    "リアクション被要求日時" = CURRENT_TIMESTAMP
WHERE
    "調査番号" = (
        SELECT MAX("調査番号")
        FROM "調査"
    )
    AND "問い合わせ調査状態" = 1;
