-- テスト：調査を終える
-- 2026-10-07
--
-- 業務上の状態：
--   対応担当者が原因を調査し、
--   原因と対応方法を確定して調査を終える。
--
-- この時点では、
--   ・問い合わせ者はまだ解決確認していない
--   ・問題解決確認日時はNULLのまま
--
-- 状態：
--   調査中
--     ↓
--   問い合わせ者確認待ち
-- =========================================================

-- =========================================================
-- ① 問題の原因と対応を確定する
-- =========================================================

UPDATE "問題"
SET
    "問題の原因" = '電源ユニットの故障',
    "情シス側での対応" = '電源ユニットを交換する',
    "問い合わせ者側で必要な対応" = 'PCの電源が入ることを確認する',
    "原因と対応の確定日時" = CURRENT_TIMESTAMP
WHERE
    "問題番号" = 1;

-- =========================================================
-- ② 問い合わせ問題の調査終了を記録する
-- =========================================================

UPDATE "問い合わせ問題"
SET
    "現在の調査状況" = '原因と対応を確定し、問い合わせ者の確認待ち',
    "調査を終えた日時" = CURRENT_TIMESTAMP
WHERE
    "問題番号" = 1
    AND "問い合わせ番号" = 1;